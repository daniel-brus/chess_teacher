DEFAULT_BOARD_SIZE = 8
DEFAULT_ICON_OPACITY = 1.0
DEFAULT_ICON_PADDING = 0.1
_ICON_SHUFFLE_SEED = 42
_SQUARE_SIZE_PX = 67


def _shuffled_icon_fragments(seed: int = _ICON_SHUFFLE_SEED) -> list[str]:
    """Return icon SVG fragments in a deterministic pseudo-random order."""
    fragments = list(ICONS.values())
    random.Random(seed).shuffle(fragments)
    return fragments


_SHUFFLED_ICON_FRAGMENTS = _shuffled_icon_fragments()


def svg_icon(
    icon_svg: str,
    x: int,
    y: int,
    size: int,
    fill: str,
    opacity: float = DEFAULT_ICON_OPACITY,
    *,
    padding_frac: float = DEFAULT_ICON_PADDING,
) -> str:
    """Render *icon_svg* centered in a square at (*x*, *y*) with side *size*."""
    padding = int(size * padding_frac)
    inner = size - 2 * padding
    return (
        f'<svg x="{x + padding}" y="{y + padding}" '
        f'width="{inner}" height="{inner}" viewBox="0 0 100 100">'
        f'<g fill="{fill}" stroke="{fill}" '
        f'fill-opacity="{opacity}" stroke-opacity="{opacity}" '
        f'stroke-width="3" stroke-linecap="round" stroke-linejoin="round">'
        f"{icon_svg.strip()}"
        f"</g></svg>"
    )


def generate_chessboard_svg(
    color1: str,
    color2: str,
    *,
    square_size: int = _SQUARE_SIZE_PX,
    board_size: int = DEFAULT_BOARD_SIZE,
    icon_opacity: float = DEFAULT_ICON_OPACITY,
    icon_padding_frac: float = DEFAULT_ICON_PADDING,
) -> tuple[str, int, int]:
    """Build a repeating chessboard tile SVG with one icon per square.

    Returns ``(svg_markup, width_px, height_px)``.
    """
    width = board_size * square_size
    height = board_size * square_size
    parts: list[str] = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}">'
    ]
    icons = cycle(_SHUFFLED_ICON_FRAGMENTS)

    for row in range(board_size):
        for col in range(board_size):
            x = col * square_size
            y = row * square_size
            light = (row + col) % 2 == 0
            square_color = color1 if light else color2
            icon_color = color2 if light else color1

            parts.append(
                f'<rect x="{x}" y="{y}" width="{square_size}" height="{square_size}" '
                f'fill="{square_color}"/>'
            )
            parts.append(
                svg_icon(
                    next(icons),
                    x,
                    y,
                    square_size,
                    icon_color,
                    opacity=icon_opacity,
                    padding_frac=icon_padding_frac,
                )
            )

    parts.append("</svg>")
    return "".join(parts), width, height
